    public static function label(string $key): string
    {
        return BackendLabelUtility::translate(self::PREFIX . $key, self::LABELS[$key] ?? $key);
    }

    /** @return array<string,string> */
    public static function translated(): array
    {
        $labels = [];
        foreach (self::LABELS as $key => $fallback) {
            $labels[$key] = BackendLabelUtility::translate(self::PREFIX . $key, $fallback);
        }

        return $labels;
    }
